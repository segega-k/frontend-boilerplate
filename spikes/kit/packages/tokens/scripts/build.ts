import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { container, font, motion, opacity, primitives, radius, roles, shadow, spacing, text } from '../src/tokens.ts';

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'generated');
mkdirSync(outDir, { recursive: true });

const header = '/* Generated by packages/tokens/scripts/build.ts. Do not edit. */\n';
const decl = (entries: [string, string][]): string => entries.map(([k, v]) => `  --${k}: ${v};`).join('\n');
const roleVars = (theme: 'light' | 'dark'): [string, string][] =>
  Object.entries(roles[theme]).map(([role, prim]) => [role, primitives[prim]]);

const rootVars: [string, string][] = [
  ...roleVars('light'),
  ['font-sans', font.sans],
  ...Object.entries(text).flatMap(([k, v]): [string, string][] => [
    [`text-${k}-size`, v.size],
    [`text-${k}-line-height`, v.lineHeight],
    [`text-${k}-weight`, v.weight],
  ]),
  ...Object.entries(spacing).map(([k, v]): [string, string] => [`space-${k}`, v]),
  ...Object.entries(container).map(([k, v]): [string, string] => [`container-${k}`, v]),
  ...Object.entries(radius).map(([k, v]): [string, string] => [`radius-${k}`, v]),
  ...Object.entries(shadow).map(([k, v]): [string, string] => [`shadow-${k}`, v]),
  ...Object.entries(motion).map(([k, v]): [string, string] => [k, v]),
  ...Object.entries(opacity).map(([k, v]): [string, string] => [`opacity-${k}`, v]),
];

const tokensCss = `${header}:root {
  color-scheme: light;
${decl(rootVars)}
}

:root[data-theme='dark'] {
  color-scheme: dark;
${decl(roleVars('dark'))}
}
`;

const themeVars: [string, string][] = [
  ...Object.keys(roles.light).map((r): [string, string] => [`color-${r}`, `var(--${r})`]),
  ['font-sans', 'var(--font-sans)'],
  ...Object.keys(text).flatMap((k): [string, string][] => [
    [`text-${k}`, `var(--text-${k}-size)`],
    [`text-${k}--line-height`, `var(--text-${k}-line-height)`],
    [`text-${k}--font-weight`, `var(--text-${k}-weight)`],
  ]),
  ...Object.keys(spacing)
    .filter((k) => k !== 'base')
    .map((k): [string, string] => [`spacing-${k}`, `var(--space-${k})`]),
  ...Object.keys(container).map((k): [string, string] => [`container-${k}`, `var(--container-${k})`]),
  ...Object.keys(radius).map((k): [string, string] => [`radius-${k}`, `var(--radius-${k})`]),
  ...Object.keys(shadow).map((k): [string, string] => [`shadow-${k}`, `var(--shadow-${k})`]),
  ['ease-standard', 'var(--ease-standard)'],
  ['ease-exit', 'var(--ease-exit)'],
  ['default-transition-duration', 'var(--duration-fast)'],
  ['default-transition-timing-function', 'var(--ease-standard)'],
  ['default-font-family', 'var(--font-sans)'],
];

const themeCss = `${header}@theme {
  --*: initial;
  --spacing: ${spacing.base};
  --breakpoint-sm: 40rem;
  --breakpoint-md: 48rem;
  --breakpoint-lg: 64rem;
}

@theme inline {
${decl(themeVars)}
}
`;

const toHex = (hex: string): string => `0x${hex.slice(1)}`;
const canvasTheme = (theme: 'light' | 'dark'): string =>
  Object.entries(roles[theme])
    .map(([role, prim]) => `    '${role}': ${toHex(primitives[prim])},`)
    .join('\n');

const canvasTs = `// Generated by packages/tokens/scripts/build.ts. Do not edit.
export const canvasColors = {
  light: {
${canvasTheme('light')}
  },
  dark: {
${canvasTheme('dark')}
  },
} as const;

export type CanvasRole = keyof typeof canvasColors.light;
`;

const twMergeTs = `// Generated by packages/tokens/scripts/build.ts. Do not edit.
export const twMergeConfig = {
  extend: {
    theme: {
      text: [${Object.keys(text)
        .map((k) => `'${k}'`)
        .join(', ')}],
      color: [${Object.keys(roles.light)
        .map((k) => `'${k}'`)
        .join(', ')}],
      radius: [${Object.keys(radius)
        .map((k) => `'${k}'`)
        .join(', ')}],
      shadow: [${Object.keys(shadow)
        .map((k) => `'${k}'`)
        .join(', ')}],
    },
  },
};
`;

writeFileSync(join(outDir, 'tokens.css'), tokensCss);
writeFileSync(join(outDir, 'theme.css'), themeCss);
writeFileSync(join(outDir, 'canvas.ts'), canvasTs);
writeFileSync(join(outDir, 'twMergeConfig.ts'), twMergeTs);
console.log('tokens: wrote', outDir);
