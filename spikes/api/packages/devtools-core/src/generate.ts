import { pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { writeFileAtomic } from './fsx.ts';
import { loadMapping, type MappingFile } from './mapping.ts';
import { generatedMappingFile, generatedTypesFile, listServices, mappingFile, specFile, type Project } from './project.ts';
import { join, relative, sep } from 'node:path';

const HEADER = '// AUTO-GENERATED by devtools-core. Do not edit: change the source and re-run the generator.\n';
const posix = (from: string, to: string): string => relative(from, to).split(sep).join('/');
const importPath = (from: string, to: string): string => {
  const rel = posix(from, to);

  return rel.startsWith('.') ? rel : `./${rel}`;
};

/** `pnpm api:gen <svc>`: committed spec → openapi-typescript `paths` (programmatic API of 7.x). */
export async function generateTypes(p: Project, svc: string): Promise<string> {
  const ast = await openapiTS(pathToFileURL(specFile(p, svc)), { rootTypes: true });
  const out = `${HEADER}// source: ${posix(p.root, specFile(p, svc))}\n\n${astToString(ast)}`;

  writeFileAtomic(p.root, generatedTypesFile(p, svc), out, p.allow);

  return out;
}

const pascal = (s: string): string => s[0]!.toUpperCase() + s.slice(1);
const q = (s: string): string => JSON.stringify(s);

function runtimeVariant(method: string, v: string): string {
  return `${method.toUpperCase()}_${v}`;
}

/** mapping JSON → `<svc>.generated.ts`: typed mapping data (`satisfies VariantsOf`), I18nParams, query/mutation factories. */
export function renderMappingTs(p: Project, mapping: MappingFile): string {
  const svc = mapping.service;
  const Svc = pascal(svc);
  const byPath = new Map<string, { method: string; operationId: string; responses: MappingFile['operations'][string]['responses'] }[]>();

  for (const [operationId, op] of Object.entries(mapping.operations)) {
    const list = byPath.get(op.path) ?? [];

    list.push({ method: op.method, operationId, responses: op.responses });
    byPath.set(op.path, list);
  }

  const lines: string[] = [];

  lines.push(HEADER + `// source: ${posix(p.root, mappingFile(p, svc))}`);
  lines.push(`import type { Client, MaybeOptionalInit } from 'openapi-fetch';`);
  lines.push(`import { callApi, type EndpointResponseMapping, type ServiceMappings, type SuccessData, type VariantsOf } from '${p.apiImport}';`);
  lines.push(`import type { paths } from '${importPath(p.mappingsDir, generatedTypesFile(p, svc))}';`);
  lines.push('');
  lines.push(`export const ${svc}Mappings = {`);

  for (const [path, ops] of [...byPath].sort(([a], [b]) => a.localeCompare(b))) {
    const responses = ops.flatMap((o) =>
      o.responses.map((r) => {
        const fields = [
          `variants: [${r.variants.map((v) => q(runtimeVariant(o.method, v))).join(', ')}]`,
          `type: ${q(r.type)}`,
          `severity: ${q(r.severity)}`,
          ...(r.support ? ['support: true'] : []),
          ...(r.i18n ? [`i18n: { title: ${q(r.i18n.title)}${r.i18n.subtitle ? `, subtitle: ${q(r.i18n.subtitle)}` : ''} }`] : []),
        ];

        return `      { ${fields.join(', ')} },`;
      }),
    );

    lines.push(`  ${q(path)}: {`, '    responses: [', ...responses, '    ],', `  } satisfies EndpointResponseMapping<VariantsOf<paths, ${q(path)}>>,`);
  }

  lines.push('} satisfies ServiceMappings;', '');

  lines.push(`/** {{params}} of the texts per path × method (from the mapping \`params\`). */`);
  lines.push(`export interface ${Svc}I18nParams {`);
  for (const [path, ops] of byPath) {
    const methods = ops
      .map((o) => {
        const params = [...new Set(o.responses.flatMap((r) => r.params ?? []))].sort();

        return params.length ? `    ${o.method.toUpperCase()}: { ${params.map((x) => `${x}: string`).join('; ')} };` : null;
      })
      .filter(Boolean);

    if (methods.length) lines.push(`  ${q(path)}: {`, ...(methods as string[]), '  };');
  }
  lines.push('}', '');

  const meta = (method: string, path: string) => `{ service: ${q(svc)}, method: ${q(method)}, path: ${q(path)} }`;

  lines.push(`export function create${Svc}Queries(client: Client<paths>) {`, '  return {');
  for (const [operationId, op] of Object.entries(mapping.operations)) {
    if (op.method !== 'get') continue;
    const P = `paths[${q(op.path)}]`;

    lines.push(
      `    ${operationId}: (init?: MaybeOptionalInit<${P}, 'get'>) => ({`,
      `      queryKey: [${q(svc)}, 'get', ${q(op.path)}, init ?? {}] as const,`,
      `      meta: ${meta('get', op.path)},`,
      `      queryFn: ({ signal }: { signal: AbortSignal }) =>`,
      `        callApi<SuccessData<${P}['get']>>(client, 'GET', ${q(op.path)}, init, signal),`,
      '    }),',
    );
  }
  lines.push('  };', '}', '');

  lines.push(`export function create${Svc}Mutations(client: Client<paths>) {`, '  return {');
  for (const [operationId, op] of Object.entries(mapping.operations)) {
    if (op.method === 'get') continue;
    const P = `paths[${q(op.path)}]`;
    const M = op.method.toUpperCase();

    lines.push(
      `    ${operationId}: () => ({`,
      `      mutationKey: [${q(svc)}, ${q(op.method)}, ${q(op.path)}] as const,`,
      `      meta: ${meta(op.method, op.path)},`,
      `      mutationFn: (init: MaybeOptionalInit<${P}, ${q(op.method)}>) =>`,
      `        callApi<SuccessData<${P}[${q(op.method)}]>>(client, ${q(M)}, ${q(op.path)}, init),`,
      '    }),',
    );
  }
  lines.push('  };', '}', '');

  return lines.join('\n');
}

export function renderIndexTs(p: Project, services: string[]): string {
  const lines = [HEADER, `import { registerMappings } from '${p.apiImport}';`];

  for (const svc of services) lines.push(`import { ${svc}Mappings } from './${svc}.generated.ts';`);
  lines.push('');
  for (const svc of services) lines.push(`registerMappings(${q(svc)}, ${svc}Mappings);`);
  lines.push('');
  for (const svc of services) lines.push(`export { create${pascal(svc)}Queries, create${pascal(svc)}Mutations, type ${pascal(svc)}I18nParams } from './${svc}.generated.ts';`);

  return `${lines.join('\n')}\n`;
}

/** `pnpm api:mappings:gen`: every `<svc>.json` → `<svc>.generated.ts` + `index.generated.ts`. */
export function generateMappings(p: Project): string[] {
  const services = listServices(p).filter((svc) => loadMapping(p, svc) !== null);

  for (const svc of services) {
    const mapping = loadMapping(p, svc);

    if (!mapping) throw new Error(`Missing ${mappingFile(p, svc)}`);
    writeFileAtomic(p.root, generatedMappingFile(p, svc), renderMappingTs(p, mapping), p.allow);
  }

  writeFileAtomic(p.root, join(p.mappingsDir, 'index.generated.ts'), renderIndexTs(p, services), p.allow);

  return services;
}
